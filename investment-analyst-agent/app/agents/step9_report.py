"""
Step 9 — Report Delivery
Serialises AnalysisState to JSON and renders an HTML summary.
Uploads both to IBM Cloud Object Storage (or saves locally as fallback).
Populates state.report_url, state.report_json, state.report_html.
"""
from __future__ import annotations

import json
import logging
from datetime import datetime

from app.models.state import AnalysisState
from app.services.storage import upload_report

logger = logging.getLogger(__name__)


_HTML_TEMPLATE = """\
<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <title>Investment Analysis Report — {tickers}</title>
  <style>
    body {{ font-family: -apple-system, 'Segoe UI', sans-serif; max-width: 900px; margin: 40px auto; color: #1f2328; }}
    h1   {{ color: #1a56db; }}
    h2   {{ border-bottom: 1px solid #e5e7eb; padding-bottom: 6px; }}
    .card {{ background: #f7f8fa; border: 1px solid #e5e7eb; border-radius: 8px; padding: 16px; margin-bottom: 16px; }}
    .buy    {{ color: #057a55; font-weight: bold; }}
    .hold   {{ color: #c27803; font-weight: bold; }}
    .reduce {{ color: #c81e1e; font-weight: bold; }}
    table {{ border-collapse: collapse; width: 100%; }}
    th,td {{ border: 1px solid #e5e7eb; padding: 8px; text-align: left; font-size: 13px; }}
    th    {{ background: #f3f4f6; }}
    .disclaimer {{ background: #fff3cd; border: 1px solid #ffc107; border-radius: 4px; padding: 12px; font-size: 12px; color: #856404; }}
    footer {{ margin-top: 40px; font-size: 11px; color: #9ca3af; text-align: center; border-top: 1px solid #e5e7eb; padding-top: 12px; }}
  </style>
</head>
<body>
  <h1>Investment Analysis Report</h1>
  <p><strong>Tickers:</strong> {tickers} &nbsp;|&nbsp; <strong>Period:</strong> {period} &nbsp;|&nbsp; <strong>Generated:</strong> {generated}</p>

  <div class="disclaimer">
    ⚠️ <strong>Disclaimer:</strong> This report is AI-generated for educational purposes only and does NOT constitute financial advice. Always consult a qualified financial advisor before making investment decisions.
  </div>

  <h2>Data Quality</h2>
  <div class="card">
    <strong>Score:</strong> {quality_score}/100<br>
    <strong>Flags:</strong> {flags}
  </div>

  <h2>AI Recommendations</h2>
  {recommendations_html}

  <h2>Key Financial Ratios</h2>
  {ratios_html}

  <h2>Risk Indicators</h2>
  {risks_html}

  <h2>Market Sentiment</h2>
  <div class="card">Overall sentiment score: <strong>{sentiment}</strong> (scale -1 to +1)</div>

  <footer>Generated by Investment Analyst Agent | Powered by IBM Granite &amp; IBM Cloud | Made with IBM Bob</footer>
</body>
</html>
"""


def _recommendation_html(state: AnalysisState) -> str:
    parts = []
    for ticker, rec in state.recommendations.items():
        css_class = rec.rating.lower()
        reasons_li = "".join(f"<li>{r}</li>" for r in rec.reasons)
        risks_li   = "".join(f"<li>{r}</li>" for r in rec.risks)
        parts.append(f"""
        <div class="card">
          <strong>{ticker}</strong> —
          <span class="{css_class}">{rec.rating}</span>
          (confidence: {rec.confidence:.0%})<br>
          <p>{rec.summary}</p>
          <strong>Reasons:</strong><ul>{reasons_li}</ul>
          <strong>Risks:</strong><ul>{risks_li}</ul>
          <small>Citations: {', '.join(rec.citations)}</small>
        </div>""")
    return "\n".join(parts) or "<p>No recommendations generated.</p>"


def _ratios_html(state: AnalysisState) -> str:
    tickers = list(state.ratios.keys())
    if not tickers:
        return "<p>No ratio data.</p>"
    headers = ["Ticker", "P/E", "P/B", "ROE", "D/E", "Volatility", "Max DD", "Beta"]
    rows = []
    for t in tickers:
        r = state.ratios[t]
        rows.append(
            f"<tr><td>{t}</td>"
            f"<td>{r.pe or '—'}</td>"
            f"<td>{r.pb or '—'}</td>"
            f"<td>{f'{r.roe*100:.1f}%' if r.roe else '—'}</td>"
            f"<td>{r.debt_to_equity or '—'}</td>"
            f"<td>{f'{r.volatility_ann*100:.1f}%' if r.volatility_ann else '—'}</td>"
            f"<td>{f'{r.max_drawdown*100:.1f}%' if r.max_drawdown else '—'}</td>"
            f"<td>{r.beta or '—'}</td></tr>"
        )
    header_row = "".join(f"<th>{h}</th>" for h in headers)
    return f"<table><thead><tr>{header_row}</tr></thead><tbody>{''.join(rows)}</tbody></table>"


def _risks_html(state: AnalysisState) -> str:
    if not state.risk_indicators:
        return "<p>No risk data.</p>"
    colour_map = {"Low": "#057a55", "Medium": "#c27803", "High": "#c81e1e"}
    rows = "".join(
        "<tr><td>{}</td><td style='color:{};font-weight:bold'>{}</td><td>{:.2f}</td><td>{}</td></tr>".format(
            r.name, colour_map.get(r.level, "#000"), r.level, r.score, r.explanation
        )
        for r in state.risk_indicators
    )
    return (
        "<table><thead><tr><th>Risk</th><th>Level</th><th>Score</th><th>Explanation</th></tr></thead>"
        f"<tbody>{rows}</tbody></table>"
    )


def run(state: AnalysisState) -> AnalysisState:
    tickers_str = ", ".join(state.primary_tickers)
    timestamp   = datetime.utcnow().strftime("%Y%m%dT%H%M%SZ")
    base_key    = f"{'-'.join(state.primary_tickers)}/{timestamp}"

    logger.info("Step 9 | generating report for %s", tickers_str)

    # ── JSON report ───────────────────────────────────────────────────────────
    # Exclude large raw data fields to keep JSON report readable
    report_data = state.model_dump(
        exclude={"price_history", "financials", "report_json", "report_html"}
    )
    report_json = json.dumps(report_data, indent=2, default=str)
    state.report_json = report_json
    json_url = upload_report(f"{base_key}/report.json", report_json, "application/json")

    # ── HTML report ───────────────────────────────────────────────────────────
    html = _HTML_TEMPLATE.format(
        tickers              = tickers_str,
        period               = state.period,
        generated            = datetime.utcnow().strftime("%Y-%m-%d %H:%M UTC"),
        quality_score        = round(state.data_quality_score, 1),
        flags                = "; ".join(state.validation_flags) or "None",
        recommendations_html = _recommendation_html(state),
        ratios_html          = _ratios_html(state),
        risks_html           = _risks_html(state),
        sentiment            = f"{state.overall_sentiment:+.3f}",
    )
    state.report_html = html
    html_url = upload_report(f"{base_key}/report.html", html, "text/html")

    state.report_url = html_url
    logger.info("Step 9 done | json=%s html=%s", json_url, html_url)
    return state
